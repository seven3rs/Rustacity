/*

   Capture reference values from the original C++ implementation of the LSAR
   audio interpolation, for the Rust port of InterpolateAudio.cpp and
   Matrix.cpp.

   This includes only src/InterpolateAudioMath.h - the arithmetic moved out of
   those two files - which is free of wxWidgets, so that it compiles on its
   own; the implementation it needs is named below for the Goldens job.  What
   it prints is appended to rust/dsp/goldens/reference.txt.

   Contributor: Sadik Pranto <pranto.smss.dev@gmail.com>

*/
// capture-sources: src/InterpolateAudioMath.cpp

#include "InterpolateAudioMath.h"

#include <cstddef>
#include <cstdio>
#include <cstdlib>
#include <vector>

namespace
{

/// The samples a case runs with: integer arithmetic narrowed to a float, so
/// that a port is reproduced on any platform.  The values span -1 to 1.
float InputSample(size_t i)
{
   return float(int((i * 37) % 129) - 64) / 64.0f;
}

/// The indices a record prints: every `stride`-th sample, with the last always
/// included.  Records carry `len` and `stride` so the Rust side rebuilds this
/// list exactly.
std::vector<size_t> Indices(size_t len, size_t stride)
{
   std::vector<size_t> idx;
   for (size_t i = 0; i < len; i += stride)
      idx.push_back(i);
   if (len > 0 && idx.back() != len - 1)
      idx.push_back(len - 1);
   return idx;
}

void PrintSamples(const float *a, const std::vector<size_t> &idx)
{
   for (auto i : idx)
      std::printf(" %.9g", double(a[i]));
}

/// The C library generator, which is where the noise the interpolation adds
/// comes from.  Nothing else in this dumper calls rand(), so the sequence a
/// seed starts is the sequence the algorithm consumes.
void RunRand(unsigned seed, size_t count)
{
   std::srand(seed);
   std::printf("interp-rand %u %d %d", seed, (int) RAND_MAX, (int) count);
   for (size_t i = 0; i < count; ++i)
      std::printf(" %d", std::rand());
   std::printf("\n");
}

/// One interpolation: the buffer is built from the sample formula, the
/// generator is seeded, the interpolation runs, and the buffer is printed
/// where it produced values.  The values it was given are regenerated by the
/// test from the same formula.
void RunCase(const char *kind, unsigned seed, size_t len, size_t firstBad,
             size_t numBad, size_t stride)
{
   std::vector<float> buffer(len);
   for (size_t i = 0; i < len; ++i)
      buffer[i] = InputSample(i);

   std::srand(seed);
   interp::InterpolateAudio(buffer.data(), len, firstBad, numBad);

   const auto idx = Indices(len, stride);
   std::printf("%s %u %d %d %d %d %d", kind, seed, (int) len, (int) firstBad,
               (int) numBad, (int) stride, (int) idx.size());
   PrintSamples(buffer.data(), idx);
   std::printf("\n");
}

}

int main()
{
   // The noise the interpolation adds is drawn from the process-global C
   // library generator, so the sequence is captured on its own: the port
   // reproduces these numbers instead of reading the application's generator,
   // which the application seeds from the clock.
   RunRand(1, 24);
   RunRand(42, 24);

   // The paths that do the least-squares autoregression: both sides of the bad
   // samples hold enough for an order of at least three.  The fourth has the
   // bad samples at the very start, which the interpolation reverses and
   // retries; the fifth has them at the very end; the last is a long run of
   // bad samples, so the order is pinned at the 50 the code allows.
   RunCase("interp-lsar", 1, 16, 8, 3, 1);
   RunCase("interp-lsar", 1, 32, 16, 1, 2);
   RunCase("interp-lsar", 1, 64, 20, 5, 4);
   RunCase("interp-lsar", 1, 64, 0, 8, 4);
   RunCase("interp-lsar", 1, 64, 56, 8, 4);
   RunCase("interp-lsar", 1, 128, 40, 40, 8);

   // Neither side holds enough good samples for that order, so these fall back
   // on the linear interpolation: the middle of a buffer, its end, and a run
   // that starts at the second sample.
   RunCase("interp-linear", 1, 6, 2, 2, 1);
   RunCase("interp-linear", 1, 5, 3, 2, 1);
   RunCase("interp-linear", 1, 7, 1, 3, 1);

   return 0;
}
