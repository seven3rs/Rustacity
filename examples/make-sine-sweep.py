"""Write examples/sine-sweep.wav, the sample the quick start runs on.

The file is generated, never recorded, so it carries no third-party audio and
can be regenerated byte for byte from this script. It uses only the standard
library: run it with any Python 3.

    python3 examples/make-sine-sweep.py [output.wav]

The sweep is mono, 44.1 kHz, 16-bit and one second long (about 88 KB), from
100 Hz to 8 kHz, at half scale so that a gain of +6 dB does not clip. The
committed file's SHA-256 is in examples/README.md; re-running this script must
reproduce it exactly.
"""

import math
import pathlib
import struct
import sys
import wave

SAMPLE_RATE = 44100
SECONDS = 1.0
FIRST_HZ = 100.0
LAST_HZ = 8000.0
AMPLITUDE = 0.5
SCALE = 32767


def samples():
    """A logarithmic sweep, as 16-bit little-endian mono frames."""
    count = int(SAMPLE_RATE * SECONDS)
    ratio = math.log(LAST_HZ / FIRST_HZ)
    phase = 0.0
    for index in range(count):
        seconds = index / SAMPLE_RATE
        hertz = FIRST_HZ * math.exp(ratio * seconds / SECONDS)
        phase += 2.0 * math.pi * hertz / SAMPLE_RATE
        yield int(round(AMPLITUDE * math.sin(phase) * SCALE))


def main() -> int:
    default = pathlib.Path(__file__).with_name("sine-sweep.wav")
    output = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default
    frames = struct.pack("<%dh" % int(SAMPLE_RATE * SECONDS), *samples())
    with wave.open(str(output), "wb") as target:
        target.setnchannels(1)
        target.setsampwidth(2)
        target.setframerate(SAMPLE_RATE)
        target.writeframes(frames)
    print(f"wrote {output} ({len(frames)} bytes of audio)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
